def _renderer_materials(r):
    mats = []
    if _isinst(r, "NiagaraSpriteRendererProperties", "NiagaraRibbonRendererProperties"):
        mats.append(_prop(r, "material"))
    elif _isinst(r, "NiagaraMeshRendererProperties"):
        for mp in _prop(r, "meshes") or []:
            for st in _prop(_prop(mp, "mesh"), "static_materials") or []:
                mats.append(_prop(st, "material_interface"))
        ov = _prop(r, "override_materials")
        if ov is not None and not isinstance(ov, (bool, int)):
            try:
                for o in ov:
                    mats.append(_prop(o, "explicit_mat"))
            except Exception:
                pass
    return [m for m in mats if m is not None]


