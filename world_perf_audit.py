@check("material_complexity", CAT_MATERIAL, "Expensive shaders (instruction count)")
def _check_material_complexity(ctx):
    mel = unreal.MaterialEditingLibrary
    if not CONFIG["material_stats"] or not hasattr(mel, "get_statistics"):
        return
    usage = list(ctx.material_usage().values())[:CONFIG["max_material_stats"]]
    per_base = OrderedDict()
    with unreal.ScopedSlowTask(len(usage), "Reading material shader statistics...") as task:
        task.make_dialog(True)
        for u in usage:
            if task.should_cancel():
                break
            task.enter_progress_frame(1, "Material stats: " + u.material.get_name())
            try:
                st = mel.get_statistics(u.material)
            except Exception:
                continue
            ps = int(_prop(st, "num_pixel_shader_instructions", 0) or 0)
            samplers = int(_prop(st, "num_samplers", 0) or 0)
            if ps <= 0:
                continue
            base = _base_material(u.material) or u.material
            e = per_base.setdefault(base.get_path_name(), {"base": base, "ps": 0, "samplers": 0, "mats": [],
                                                           "comps": [], "translucent": False, "systems": []})
            e["ps"] = max(e["ps"], ps)
            e["samplers"] = max(e["samplers"], samplers)
            e["mats"].append(u.material)
            e["comps"] += u.comps
            e["systems"] += u.systems
            e["translucent"] = e["translucent"] or _is_translucent(u.material)
    for e in per_base.values():
        ps, base = e["ps"], e["base"]
        if e["translucent"]:
            warn, high = CONFIG["translucent_ps_warn"], CONFIG["translucent_ps_warn"] * 2
        else:
            warn, high = CONFIG["ps_instructions_warn"], CONFIG["ps_instructions_high"]
        heavy_samplers = e["samplers"] > CONFIG["samplers_warn"]
        if ps < warn and not heavy_samplers:
            continue
        sev = HIGH if ps >= high else (MEDIUM if ps >= warn else LOW)
        extra = (" Translucent: this cost is paid once per overlapping layer (overdraw)%s."
                 % (", and it's used by particles" if e["systems"] else "")) if e["translucent"] else ""
        yield Issue(
            "material_complexity", CAT_MATERIAL, sev, "Expensive material", base.get_name(),
            detail=("Up to %d pixel-shader instructions and %d samplers (%d instance(s) in this level).%s"
                    % (ps, e["samplers"], len(e["mats"]), extra)),
            solution=("Open the material and check Stats / Platform Stats. Typical wins: Static Switches instead "
                      "of lerping between whole branches, move math to the vertex shader (Custom UVs / Vertex "
                      "Interpolator), pack masks into one texture, Shared:Wrap samplers, cheaper quality-switch "
                      "paths, and use Shader Complexity view to find the hot spots."),
            metric="%d instr" % ps, cost=_score(sev, _mag_log(ps * max(1, len(e["comps"])), warn, high * 200)),
            targets=e["comps"], assets=[base])


