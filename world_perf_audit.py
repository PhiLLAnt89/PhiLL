def show(reuse=True):
    """Open the tool window (offers to install PySide6 if Qt is missing).
    reuse=False closes an already open window first (used when the file is re-run after editing CONFIG)."""
    qt = _load_qt()
    if qt is None:
        r = unreal.EditorDialog.show_message(
            TOOL_NAME,
            "The UI needs Qt for Python (PySide6), which Unreal doesn't ship.\n\n"
            "Yes: install PySide6 now (one-time, ~100 MB, into\n%s)\n"
            "No: run in text mode (report in the Output Log + HTML file)." % _deps_dir(),
            unreal.AppMsgType.YES_NO_CANCEL)
        if r == unreal.AppReturnType.YES:
            if install_pyside6():
                qt = _load_qt()
        elif r == unreal.AppReturnType.NO:
            run_text_mode()
            return None
        if qt is None:
            return None
    QtCore, QtGui, QtWidgets = qt
    app = QtWidgets.QApplication.instance() or QtWidgets.QApplication([])
    for w in app.topLevelWidgets():
        if w.objectName() == WINDOW_OBJECT_NAME:
            if reuse:
                w.show()
                w.raise_()
                w.activateWindow()
                return w
            w.close()
            w.deleteLater()
    win = _make_window_class(QtCore, QtGui, QtWidgets)()
    win.show()
    try:
        unreal.parent_external_window_to_slate(int(win.winId()))
    except Exception:
        pass
    _start_qt_tick(QtWidgets)
    # Keep the app + window alive. Unreal runs script files in a private namespace that can be
    # garbage-collected after the run, so the references go on the sys module, which lives forever.
    keep = sys.__dict__.setdefault("_world_perf_audit_keep", {})
    keep["app"], keep["window"] = app, win
    _STATE["window"] = win
    return win


