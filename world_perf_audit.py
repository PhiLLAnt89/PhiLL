_PROJECT_MOUNTS = None


def _project_mounts():
    """Content roots we are allowed to modify: /Game plus the project's own plugins."""
    global _PROJECT_MOUNTS
    if _PROJECT_MOUNTS is None:
        mounts = {"Game"}
        try:
            plug_dir = unreal.Paths.convert_relative_path_to_full(unreal.Paths.project_plugins_dir())
            for root, dirs, files in os.walk(plug_dir):
                if root[len(plug_dir):].count(os.sep) > 3:
                    dirs[:] = []
                    continue
                for f in files:
                    if f.lower().endswith(".uplugin"):
                        mounts.add(os.path.splitext(f)[0])
        except Exception:
            pass
        _PROJECT_MOUNTS = mounts
    return _PROJECT_MOUNTS


def _is_editable_asset(obj):
    try:
        parts = obj.get_outermost().get_name().split("/")
    except Exception:
        return False
    return len(parts) > 1 and parts[1] in _project_mounts()


