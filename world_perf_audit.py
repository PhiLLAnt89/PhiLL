def _ser(v):
    if v is None or isinstance(v, (bool, int, float, str)):
        return {"t": "py", "v": v}
    etype, name = type(v).__name__, _enum_name(v)
    if _enum_member(_ucls(etype), name) is not None:
        return {"t": "enum", "e": etype, "v": name}
    raise TypeError("Can't record %r for revert" % (v,))


def _deser(d):
    if not isinstance(d, dict):
        raise RuntimeError("Malformed journal value")
    if d.get("t") == "enum":
        if d.get("e") not in _JOURNAL_ENUMS or not re.match(r"^[A-Z0-9_]{1,64}$", str(d.get("v"))):
            raise RuntimeError("Journal enum not allowed: %s.%s" % (d.get("e"), d.get("v")))
        val = _enum_member(_ucls(d["e"]), d["v"])
        if val is None:
            raise RuntimeError("Unknown enum value %s.%s" % (d["e"], d["v"]))
        return val
    v = d.get("v")
    if v is None or isinstance(v, (bool, int, float)):
        return v
    raise RuntimeError("Journal value not allowed: %r" % (v,))


def _check_journal_change(ch):
    """Reject anything this tool would never have written (tampered or corrupt journal)."""
    k = ch.get("k")
    if ch.get("post") not in _JOURNAL_POSTS:
        raise RuntimeError("journal: unexpected post step %r" % ch.get("post"))
    if k in ("prop", "call", "struct", "nanite", "lods", "dfscale") and not isinstance(ch.get("path"), str):
        raise RuntimeError("journal: missing object path")
    if k == "prop" and ch.get("prop") not in _JOURNAL_PROPS:
        raise RuntimeError("journal: property %r not allowed" % ch.get("prop"))
    if k == "call" and (ch.get("setter") not in _JOURNAL_SETTERS or not isinstance(ch.get("old"), list)
                        or len(ch["old"]) > 2):
        raise RuntimeError("journal: setter %r not allowed" % ch.get("setter"))
    if k == "struct" and (ch.get("prop") not in _JOURNAL_STRUCTS or not re.match(
            r"^(override_[a-z0-9_]{1,64}|min|max)$", str(ch.get("field")))):
        raise RuntimeError("journal: struct field %r.%r not allowed" % (ch.get("prop"), ch.get("field")))
    if k == "nanite" and not isinstance(ch.get("old"), bool):
        raise RuntimeError("journal: bad Nanite value")
    if k == "cvar":
        if ch.get("name") not in _ALLOWED_CVARS:
            raise RuntimeError("journal: console variable %r not allowed" % ch.get("name"))
        for v in (ch.get("old"), ch.get("ini_old")):
            if v is not None and not _NUMBER_RE.match(str(v)):
                raise RuntimeError("journal: bad console variable value %r" % (v,))
    if k == "scal":
        name, sections = ch.get("name"), ch.get("sections")
        if name not in _ALLOWED_CVARS or not isinstance(sections, list) or not 0 < len(sections) <= 6:
            raise RuntimeError("journal: quality-level change %r not allowed" % (name,))
        for item in sections:
            m = _SCAL_SECTION_RE.match(str(item[0])) if isinstance(item, list) and len(item) == 2 else None
            if m is None or m.group(1) != _CVAR_GROUP.get(name):
                raise RuntimeError("journal: scalability section %r not allowed" % (item,))
            if item[1] is not None and not _NUMBER_RE.match(str(item[1])):
                raise RuntimeError("journal: bad scalability value %r" % (item[1],))
        if ch.get("old") is not None and not _NUMBER_RE.match(str(ch["old"])):
            raise RuntimeError("journal: bad console variable value %r" % (ch["old"],))
    if k == "dfscale" and (not isinstance(ch.get("old"), (int, float)) or isinstance(ch.get("old"), bool)
                           or not 0.0 < float(ch["old"]) <= 100.0):
        raise RuntimeError("journal: bad distance field resolution %r" % (ch.get("old"),))
    if k == "ini":
        if (ch.get("section"), ch.get("key")) not in _ALLOWED_INI or ch.get("file", "DefaultEngine.ini") != "DefaultEngine.ini":
            raise RuntimeError("journal: ini key %r not allowed" % ch.get("key"))
        if ch.get("old") is not None and not re.match(r"^[A-Za-z0-9_.\-]{0,32}$", str(ch["old"])):
            raise RuntimeError("journal: bad ini value %r" % (ch["old"],))


class ChangeRecorder(object):
    """Handed to every fix. Records the old value *before* anything is changed."""

    def __init__(self):
        self.changes = []

    def set(self, obj, prop, value, post=None, notify=True):
        self.changes.append({"k": "prop", "path": obj.get_path_name(), "prop": prop, "label": _label(obj),
                             "old": _ser(obj.get_editor_property(prop)), "post": post})
        _modify(obj)
        _set(obj, prop, value, notify)

    def call(self, obj, setter, new_args, old_args, post=None):
        self.changes.append({"k": "call", "path": obj.get_path_name(), "setter": setter, "label": _label(obj),
                             "old": [_ser(a) for a in old_args], "post": post})
        _modify(obj)
        getattr(obj, setter)(*new_args)

    def struct_field(self, owner, struct_prop, field, value):
        st = owner.get_editor_property(struct_prop)
        self.changes.append({"k": "struct", "path": owner.get_path_name(), "prop": struct_prop, "field": field,
                             "label": _label(owner), "old": _ser(st.get_editor_property(field))})
        _modify(owner)
        st.set_editor_property(field, value)
        owner.set_editor_property(struct_prop, st)

    def note(self, kind, **data):
        d = {"k": kind}
        d.update(data)
        self.changes.append(d)

    def scalability(self, name, value, group, levels):
        """Write name=value into Config/DefaultScalability.ini for these quality levels of `group` only (the other
        levels keep their values) and apply it now if the editor runs at one of them. Old values are recorded.
        Returns (applied_now, editor_level)."""
        cur = max(0, min(4, _cvar_int(_GROUP_LEVEL_CVAR[group], 3)))
        live = cur in levels
        sections = [s for lv in levels for s in _scalability_sections(group, lv)]
        self.changes.append({"k": "scal", "name": name, "label": "%s (%s quality)" % (name, _level_label(levels)),
                             "sections": [[s, _get_project_ini(s, name, "DefaultScalability.ini")] for s in sections],
                             "old": _cvar_str(name) if live else None, "live": live})
        for s in sections:
            _set_project_ini(s, name, str(value), "DefaultScalability.ini")
        if live:
            _run_console("%s %s" % (name, value))
        return live, cur

    def df_scale(self, mesh, value):
        """Distance Field Resolution Scale of LOD0's build settings (rebuilds the mesh's distance field)."""
        old = _df_scale(mesh)
        if old is None:
            raise RuntimeError("Can't read the build settings of %s" % mesh.get_name())
        self.changes.append({"k": "dfscale", "path": mesh.get_path_name(), "label": mesh.get_name(), "old": old})
        _set_df_scale(mesh, value)


def _cvar_str(name):
    try:
        v = float(unreal.SystemLibrary.get_console_variable_float_value(name))
        return str(int(v)) if v.is_integer() else ("%g" % v)
    except Exception:
        return None


