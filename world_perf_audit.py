def _is_visible(comp):
    try:
        if not comp.is_visible():
            return False
    except Exception:
        pass
    if _prop(comp, "hidden_in_game", False):
        return False
    try:
        owner = comp.get_owner()
        if owner is not None and _prop(owner, "hidden", False):
            return False
    except Exception:
        pass
    return True


