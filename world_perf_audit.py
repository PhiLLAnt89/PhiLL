@check("light_stationary_overlap", CAT_LIGHT, "Stationary light overlap (approx.)")
def _check_stationary_overlap(ctx):
    if not _cvar_int("r.AllowStaticLighting", 1):
        return
    stat = [c for c in _local_lights(ctx) if _mobility(c) == "STATIONARY" and _prop(c, "cast_shadows", False)]
    dirs = [c for c in ctx.visible("DirectionalLightComponent")
            if _mobility(c) == "STATIONARY" and _prop(c, "cast_shadows", False)]
    if len(stat) + len(dirs) <= 4:
        return
    info = []
    for c in stat:
        try:
            info.append((c, c.get_world_location(), float(_prop(c, "attenuation_radius", 0.0) or 0.0)))
        except Exception:
            pass
    crowded, worst = [], 0
    for c, loc, r in info:
        n = len(dirs) + sum(1 for o, oloc, orad in info if o is not c and _dist(loc, oloc) < r + orad)
        if n + 1 > 4:
            crowded.append(c)
            worst = max(worst, n + 1)
    if not crowded:
        return
    yield Issue(
        "light_stationary_overlap", CAT_LIGHT, MEDIUM, "Stationary lights may overlap > 4",
        "%d lights" % len(crowded),
        detail=("Up to %d stationary shadow-casting lights (incl. %d directional) overlap each other. Only 4 can "
                "overlap; the extras fall back to fully dynamic shadows (red X in the Stationary Light Overlap "
                "view mode). Approximate check based on attenuation spheres: %s"
                % (worst, len(dirs), _names(crowded))),
        solution=("Check View Mode > Optimization Viewmodes > Stationary Light Overlap. Shrink radii, make some "
                  "lights Static, or disable shadows on the least important ones."),
        metric="up to %d overlap" % worst, cost=_score(MEDIUM, (worst - 4) / 8.0), targets=crowded)


