_STATE = {"issues": [], "stats": OrderedDict(), "errors": [], "level": ""}


def _get_actors(selected_only=False):
    sub = unreal.get_editor_subsystem(unreal.EditorActorSubsystem)
    actors = sub.get_selected_level_actors() if selected_only else sub.get_all_level_actors()
    return [a for a in (actors or []) if a is not None]


def scan(selected_only=False, check_keys=None):
    """Run all enabled checks. Returns the issue list (sorted by cost, highest first)."""
    actors = _get_actors(selected_only)
    ctx = ScanContext(actors)
    checks = [c for c in _CHECKS if (c["key"] in check_keys if check_keys else c["enabled"])]
    issues, errors = [], []
    with unreal.ScopedSlowTask(len(checks) + 1, "%s: scanning..." % TOOL_NAME) as task:
        task.make_dialog(True)
        task.enter_progress_frame(1, "Collecting %d actors..." % len(actors))
        for c in checks:
            if task.should_cancel():
                break
            task.enter_progress_frame(1, c["name"])
            try:
                for issue in (c["fn"](ctx) or []):
                    issues.append(issue)
            except Exception:
                errors.append((c["name"], traceback.format_exc()))
                _warn("Check '%s' failed:\n%s" % (c["name"], traceback.format_exc()))
    try:
        ctx.build_stats()
    except Exception:
        pass
    issues.sort(key=lambda i: (-i.cost, -i.severity, i.title))
    world = _editor_world()
    _STATE.update(issues=issues, stats=ctx.stats, errors=errors,
                  level=world.get_name() if world else "", selected_only=selected_only)
    _log("Scan done: %d issue(s), %d auto-fixable, %d check error(s)."
         % (len(issues), sum(1 for i in issues if i.fixable), len(errors)))
    return issues


def apply_fixes(issues, title="World Perf Audit: Fix"):
    """Apply fixes inside one undo transaction. Returns (fixed, failed)."""
    todo = [i for i in issues if i.fixable]
    fixed = failed = 0
    if not todo:
        return 0, 0
    with unreal.ScopedEditorTransaction(title):
        with unreal.ScopedSlowTask(len(todo), "Applying fixes...") as task:
            task.make_dialog(True)
            for issue in todo:
                if task.should_cancel():
                    break
                task.enter_progress_frame(1, "Fixing: %s - %s" % (issue.title, issue.obj))
                try:
                    msg = issue.fix()
                    issue.status, issue.message = "fixed", (msg or issue.fix_label)
                    fixed += 1
                    _log("Fixed #%d %s (%s): %s" % (issue.id, issue.title, issue.obj, issue.message))
                except Exception as e:
                    issue.status, issue.message = "failed", str(e)
                    failed += 1
                    _warn("Fix failed #%d %s (%s): %s\n%s" % (issue.id, issue.title, issue.obj, e,
                                                              traceback.format_exc()))
    return fixed, failed


def go_to(issue):
    """Select + frame the actors involved, and/or show the assets in the Content Browser."""
    actors = []
    for t in issue.targets:
        try:
            a = t if isinstance(t, unreal.Actor) else t.get_owner()
            if a is not None and a not in actors:
                actors.append(a)
        except Exception:
            pass
    if actors:
        try:
            unreal.get_editor_subsystem(unreal.EditorActorSubsystem).set_selected_level_actors(actors[:500])
            unreal.SystemLibrary.execute_console_command(_editor_world(), "CAMERA ALIGN ACTIVEVIEWPORTONLY")
        except Exception as e:
            _warn("Go To failed: %s" % e)
    if issue.assets:
        try:
            unreal.EditorAssetLibrary.sync_browser_to_objects([a.get_path_name() for a in issue.assets])
        except Exception:
            pass


def open_assets(issue):
    if issue.assets:
        try:
            unreal.get_editor_subsystem(unreal.AssetEditorSubsystem).open_editor_for_assets(issue.assets)
        except Exception as e:
            _warn("Open failed: %s" % e)


