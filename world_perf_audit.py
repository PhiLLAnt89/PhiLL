_BPP = {"TC_DEFAULT": 1.0, "TC_NORMALMAP": 1.0, "TC_MASKS": 1.0, "TC_GRAYSCALE": 1.0, "TC_DISPLACEMENTMAP": 1.0,
        "TC_VECTOR_DISPLACEMENTMAP": 4.0, "TC_HDR": 8.0, "TC_HDR_F32": 16.0, "TC_HDR_COMPRESSED": 1.0,
        "TC_BC7": 1.0, "TC_ALPHA": 0.5, "TC_EDITOR_ICON": 4.0, "TC_SINGLE_FLOAT": 4.0, "TC_HALF_FLOAT": 2.0}
_NO_MIP_GROUPS = ("TEXTUREGROUP_UI", "TEXTUREGROUP_PIXELS2D", "TEXTUREGROUP_COLORLOOKUPTABLE")


def _tex_size(tex):
    try:
        return int(tex.blueprint_get_size_x()), int(tex.blueprint_get_size_y())
    except Exception:
        return 0, 0


def _texture_bytes(tex):
    w, h = _tex_size(tex)
    bpp = _BPP.get(_enum_name(_prop(tex, "compression_settings")), 1.0)
    mips = 1.0 if _enum_name(_prop(tex, "mip_gen_settings")) == "TMGS_NO_MIPMAPS" else 1.333
    return int(w * h * bpp * mips)


def _textures2d(ctx):
    for e in ctx.textures().values():
        tex = e["tex"]
        if _isinst(tex, "Texture2D"):
            yield tex, e["materials"]


def _tex_issue(check_key, sev, title, tex, mats, detail, solution, metric, magnitude, fix=None, fix_label=""):
    editable = _is_editable_asset(tex)
    return Issue(
        check_key, CAT_TEXTURE, sev, title, tex.get_name(),
        detail=detail + "\nUsed by: %s" % ", ".join(mats[:5]),
        solution=solution + ("" if editable else _READONLY_NOTE),
        metric=metric, cost=_score(sev, magnitude), assets=[tex],
        fix=fix if editable else None, fix_label=fix_label)


def _tex_setter(tex, **props):
    def fix():
        _modify(tex)
        for k, v in props.items():
            _set(tex, k, v)   # PostEditChange recompresses the texture
        return ", ".join("%s=%s" % (k, _enum_name(v) if not isinstance(v, (int, float, bool)) else v)
                         for k, v in props.items())
    return fix


@check("tex_oversized", CAT_TEXTURE, "Oversized textures")
def _check_tex_oversized(ctx):
    for tex, mats in _textures2d(ctx):
        w, h = _tex_size(tex)
        size = max(w, h)
        if size < CONFIG["texture_warn_size"]:
            continue
        if size >= CONFIG["texture_critical_size"]:
            sev, clamp = HIGH, CONFIG["texture_critical_clamp"]
        else:
            sev, clamp = LOW, CONFIG["texture_warn_clamp"]
        cur_max = int(_prop(tex, "max_texture_size", 0) or 0)
        if 0 < cur_max <= clamp:
            continue
        if _prop(tex, "virtual_texture_streaming", False):
            sev = INFO
        mb = _texture_bytes(tex)
        yield _tex_issue(
            "tex_oversized", sev, "%dK texture" % (size // 1024), tex, mats,
            detail=("%dx%d, ~%s of GPU memory with mips. Large textures fill the streaming pool, cause blurry "
                    "mips elsewhere ('Texture streaming pool over budget') and slow loading." % (w, h, _fmt_bytes(mb))),
            solution=("Texture Editor > Compression > Maximum Texture Size = %d (non-destructive, source stays), "
                      "or use Virtual Texture Streaming for genuinely huge maps." % clamp),
            metric="%dx%d ~%s" % (w, h, _fmt_bytes(mb)), magnitude=_mag_log(mb, 8 << 20, 512 << 20),
            fix=_tex_setter(tex, max_texture_size=clamp), fix_label="Set Maximum Texture Size = %d" % clamp)


