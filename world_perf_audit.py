class ScanContext(object):
    """Collects scene data once; checks read from here."""

    def __init__(self, actors, templates=None):
        self.actors = [a for a in actors if a is not None]
        # Sequencer spawnable templates: they live in the sequence asset, so fixes on them stick. Only the actor
        # checks in _TEMPLATE_CHECKS see them (no bounds/positions: a template isn't placed). Asset checks and counts
        # use the spawned copy instead, so nothing is counted twice.
        self.templates = [t for t in (templates or []) if t is not None]
        self.allow_templates = False
        self.found = []                 # issues found so far in this scan (for checks that group earlier ones)
        self._editable = None
        self._components = {}
        self._mesh_usage = None
        self._mat_usage = None
        self._niagara = None
        self._renderers = None
        self._wpo = {}
        self._wpo_comps = None
        self._textures = None
        self.stats = OrderedDict()

    # --- generic -------------------------------------------------------------
    def _actors(self, include_readonly):
        if include_readonly:
            return self.actors
        if self._editable is None:
            ro = set(_READONLY_ACTORS)
            self._editable = [a for a in self.actors if a.get_path_name() not in ro] if ro else self.actors
        return self._editable + self.templates if self.allow_templates else self._editable

    def components(self, class_name, include_readonly=False):
        """Components of the scanned actors. Actor-level checks (they change components) leave out
        Level Instance contents / child actors / Sequencer spawnables; asset-level ones pass include_readonly."""
        cls = _ucls(class_name)
        if cls is None:
            return []
        key = (class_name, bool(include_readonly), self.allow_templates and not include_readonly)
        cached = self._components.get(key)
        if cached is None:
            cached = []
            for a in self._actors(include_readonly):
                try:
                    comps = a.get_components_by_class(cls)
                except Exception:
                    comps = None
                if comps:
                    cached.extend(c for c in comps if c is not None)
            self._components[key] = cached
        return cached

    def visible(self, class_name, include_readonly=False):
        return [c for c in self.components(class_name, include_readonly) if _is_visible(c)]

    def actors_of(self, class_name, include_readonly=False):
        cls = _ucls(class_name)
        return [a for a in self._actors(include_readonly) if cls is not None and isinstance(a, cls)]

    @staticmethod
    def component_materials(comp):
        out = []
        try:
            n = comp.get_num_materials()
        except Exception:
            n = 0
        for i in range(n):
            try:
                m = comp.get_material(i)
            except Exception:
                m = None
            if m is not None:
                out.append(m)
        return out

    # --- meshes --------------------------------------------------------------
    def mesh_usage(self):
        """path -> {"mesh", "comps", "instances"} for visible static mesh components."""
        if self._mesh_usage is None:
            usage = OrderedDict()
            for c in self.visible("StaticMeshComponent", include_readonly=True):
                mesh = _prop(c, "static_mesh")
                if mesh is None:
                    continue
                u = usage.setdefault(mesh.get_path_name(), {"mesh": mesh, "comps": [], "instances": 0})
                u["comps"].append(c)
                n = 1
                if _isinst(c, "InstancedStaticMeshComponent"):
                    try:
                        n = int(c.get_instance_count())
                    except Exception:
                        n = 0
                u["instances"] += n
            self._mesh_usage = usage
        return self._mesh_usage

    # --- niagara -------------------------------------------------------------
    def niagara_systems(self):
        """[(system, [components])]"""
        if self._niagara is None:
            res = OrderedDict()
            for c in self.components("NiagaraComponent", include_readonly=True):
                try:
                    s = c.get_asset()
                except Exception:
                    s = _prop(c, "asset")
                if s is None:
                    continue
                res.setdefault(s.get_path_name(), [s, []])[1].append(c)
            self._niagara = [(v[0], v[1]) for v in res.values()]
        return self._niagara

    def niagara_renderers(self, system):
        """Renderer property objects living inside the system asset."""
        if self._renderers is None:
            self._renderers = {}
            cls = _ucls("NiagaraRendererProperties")
            pkgs = set()
            for s, _ in self.niagara_systems():
                try:
                    pkgs.add(s.get_outermost().get_name())
                except Exception:
                    pass
            if cls is not None and pkgs and hasattr(unreal, "ObjectIterator"):
                for r in unreal.ObjectIterator(cls):
                    try:
                        pn = r.get_outermost().get_name()
                    except Exception:
                        continue
                    if pn in pkgs and not r.get_name().startswith("Default__"):
                        self._renderers.setdefault(pn, []).append(r)
        try:
            return self._renderers.get(system.get_outermost().get_name(), [])
        except Exception:
            return []

    # --- materials -----------------------------------------------------------
    def material_usage(self):
        if self._mat_usage is None:
            usage = OrderedDict()

            def add(mat, comp=None, system=None, skeletal=False):
                if mat is None:
                    return
                u = usage.get(mat.get_path_name())
                if u is None:
                    u = usage[mat.get_path_name()] = _MatUse(mat)
                if comp is not None:
                    u.comps.append(comp)
                if system is not None and system not in u.systems:
                    u.systems.append(system)
                u.skeletal = u.skeletal or skeletal

            for c in self.visible("StaticMeshComponent", include_readonly=True):
                for m in self.component_materials(c):
                    add(m, c)
            for c in self.visible("SkeletalMeshComponent", include_readonly=True):
                for m in self.component_materials(c):
                    add(m, c, skeletal=True)
            for system, comps in self.niagara_systems():
                for r in self.niagara_renderers(system):
                    for m in _renderer_materials(r):
                        add(m, comps[0] if comps else None, system=system)
            for c in self.visible("DecalComponent", include_readonly=True):
                add(_prop(c, "decal_material"), c)
            self._mat_usage = usage
        return self._mat_usage

    def uses_wpo(self, mi):
        base = _base_material(mi)
        if base is None:
            return False
        key = base.get_path_name()
        if key not in self._wpo:
            res = False
            try:
                node = unreal.MaterialEditingLibrary.get_material_property_input_node(
                    base, unreal.MaterialProperty.MP_WORLD_POSITION_OFFSET)
                res = node is not None
            except Exception:
                res = False
            self._wpo[key] = res
        return self._wpo[key]

    def wpo_components(self):
        if self._wpo_comps is None:
            self._wpo_comps = {}
        key = self.allow_templates
        if key not in self._wpo_comps:
            self._wpo_comps[key] = [c for c in self.visible("MeshComponent")
                                    if any(self.uses_wpo(m) for m in self.component_materials(c))]
        return self._wpo_comps[key]

    # --- textures ------------------------------------------------------------
    def textures(self):
        """texture path -> {"tex": Texture, "materials": [material names]} for materials in the scene."""
        if self._textures is None:
            self._textures = OrderedDict()
            try:
                ar = unreal.AssetRegistryHelpers.get_asset_registry()
                opts = unreal.AssetRegistryDependencyOptions(
                    include_soft_package_references=False, include_hard_package_references=True,
                    include_searchable_names=False, include_soft_management_references=False,
                    include_hard_management_references=False)
            except Exception as e:
                _warn("Asset registry unavailable, texture checks skipped: %s" % e)
                return self._textures
            memo = {}

            def asset_class(ad):
                p = getattr(ad, "asset_class_path", None)
                if p is not None:
                    try:
                        return str(p.asset_name)
                    except Exception:
                        pass
                try:
                    return str(ad.asset_class)
                except Exception:
                    return ""

            def textures_of(pkg, depth=0):
                if pkg in memo:
                    return memo[pkg]
                memo[pkg] = found = []
                if depth > 12:
                    return found
                try:
                    deps = ar.get_dependencies(pkg, opts) or []
                except Exception:
                    deps = []
                for dep in deps:
                    dep = str(dep)
                    if dep.startswith("/Script/"):
                        continue
                    try:
                        ads = ar.get_assets_by_package_name(dep) or []
                    except Exception:
                        ads = []
                    for ad in ads:
                        cname = asset_class(ad)
                        if cname.startswith("Texture"):
                            found.append(ad)
                        elif cname.startswith("Material"):
                            found.extend(textures_of(dep, depth + 1))
                return found

            for u in self.material_usage().values():
                try:
                    pkg = u.material.get_outermost().get_name()
                except Exception:
                    continue
                for ad in textures_of(pkg):
                    try:
                        tex = ad.get_asset()
                    except Exception:
                        tex = None
                    if tex is None:
                        continue
                    e = self._textures.setdefault(tex.get_path_name(), {"tex": tex, "materials": [], "fx": False})
                    if u.material.get_name() not in e["materials"]:
                        e["materials"].append(u.material.get_name())
                    e["fx"] = e["fx"] or bool(u.systems)
        return self._textures

    # --- summary -------------------------------------------------------------
    def build_stats(self):
        s = self.stats
        s["Actors"] = _fmt_count(len(self.actors))
        try:
            mu = self.mesh_usage()
            nn_tris, nanite = 0, 0
            for u in mu.values():
                if _nanite_enabled(u["mesh"]):
                    nanite += 1
                else:
                    nn_tris += _mesh_tris(u["mesh"]) * max(1, u["instances"])
            s["Static meshes"] = "%d (%d Nanite)" % (len(mu), nanite)
            s["Non-Nanite tris"] = _fmt_count(nn_tris)
        except Exception:
            pass
        shadowed = 0
        for c in self.visible("LocalLightComponent"):
            if _prop(c, "cast_shadows", False) and _mobility(c) != "STATIC":
                shadowed += 1
        s["Shadowed dynamic lights"] = str(shadowed)
        s["Niagara systems"] = str(len(self.niagara_systems()))
        if self._mat_usage is not None:
            s["Materials"] = str(len(self._mat_usage))
        if self._textures:
            total = sum(_texture_bytes(e["tex"]) for e in self._textures.values())
            s["Textures"] = "%d (~%s)" % (len(self._textures), _fmt_bytes(total))
        return s


