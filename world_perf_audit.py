"""
World Performance Audit  -  Unreal Engine 5.6 editor tool (single Python script, Qt UI)
=======================================================================================

Scans the open level for setups that cost performance (plus the motion-vector /
velocity problems that cause TSR ghosting on particles and WPO meshes), ranks
every issue by estimated cost, explains it and gives you a "Fix" button.

HOW TO RUN  (enable "Python Editor Script Plugin" + "Editor Scripting Utilities" first)
----------
A) Paste: Window > Output Log, set the dropdown left of the input box to "Python"
   (not "Cmd", not "Python (REPL)"), paste this whole script, press Enter.
B) File:  save it as world_perf_audit with the Python file extension, then
   Tools > Execute Python Script... and pick it.
C) Module: put that file in <Project>/Content/Python/ and run in the Output Log:
      import world_perf_audit; world_perf_audit.show()

NOTE: this script never spells out the Python file extension on purpose. When
code is pasted into the Output Log, Unreal treats any text containing it as a
file path and fails with "Could not load Python file".

QT
--
The UI uses PySide6 (PyQt6 / PySide2 / PyQt5 also work). Unreal's Python does
not ship Qt: if none is found the script offers to pip-install PySide6 once into
a per-user folder (outside your project). If you say no, it runs in text mode:
the report is printed to the Output Log / exported as HTML and you can fix from
Python:   world_perf_audit.fix(12), fix_all(), revert(12), revert_all(),
          recover_previous_fixes(apply=True)

FIX SAFETY
----------
Every fix is labelled with its impact: "Safe" (no visual change), "Visual"
(changes the look, warning icon next to Fix) or "Behaviour" (can change
gameplay). Fix one row, "Fix Selected" (multi-select), "Fix Safe" (only Safe
fixes) or "Fix All Shown" (the whole filtered list). No popups.
Every fix records the old values in Saved/PerfAudit/fix_journal.json, so
Revert works even after saving or restarting (Revert > Revert ALL...).
Fixes made by the first version of this tool (no journal) can be undone with
Revert > "Undo fixes made by the previous version", which reads Saved/Logs.
Asset-level fixes (Nanite, LODs, textures, materials, Niagara) change the asset
for every level that uses it - nothing is saved until you click Save.

GPU PROFILE: "Profile GPU" (or world_perf_audit.profile_gpu()) captures frames
with the CSV profiler, reports GPU/game/render-thread bound and the expensive
GPU passes (shadows, Lumen, translucency...), linked to the scan findings.

SCOPE: the persistent level + every LOADED sublevel (visible or hidden), Level
Instance contents, child actors and spawned Sequencer spawnables. Unloaded
sublevels / World Partition regions and runtime-spawned actors are not scanned;
the header lists any sublevel that isn't loaded. Thresholds live in CONFIG below.
"""

