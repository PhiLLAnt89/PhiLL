def analyse_csv(path):
    """Average every numeric column of an Unreal CSV profile. Returns {'frames', 'means', 'path'}.
    Unreal writes a first header, the frame rows, a '[HasHeaderRowAtEnd]...' metadata row and - because stats can
    appear after the first frame - the complete header again at the end. The longest header wins."""
    with open(path, "r", encoding="utf-8", errors="replace", newline="") as fh:
        rows = [r for r in csv.reader(fh) if r]
    if not rows:
        raise RuntimeError("Empty CSV profile: %s" % path)

    def numeric_share(r):
        n = 0
        for v in r:
            try:
                float(v)
                n += 1
            except ValueError:
                pass
        return n / float(max(1, len(r)))

    headers = [r for r in rows if not r[0].strip().startswith("[") and numeric_share(r) < 0.5]
    header = [h.strip() for h in max(headers, key=len)] if headers else [h.strip() for h in rows[0]]
    sums, counts, frames = {}, {}, 0
    for r in rows:
        if r[0].strip().startswith("[") or numeric_share(r) < 0.5:
            continue                                  # metadata / header rows
        numeric = 0
        for i, v in enumerate(r[:len(header)]):
            try:
                f = float(v)
            except ValueError:
                continue
            numeric += 1
            sums[header[i]] = sums.get(header[i], 0.0) + f
            counts[header[i]] = counts.get(header[i], 0) + 1
        if numeric:
            frames += 1
    means = OrderedDict((k, sums[k] / counts[k]) for k in header if counts.get(k))
    return {"frames": frames, "means": means, "path": path}


def _mean(means, *names):
    low = {k.lower(): v for k, v in means.items()}
    for n in names:
        if n.lower() in low:
            return low[n.lower()]
    return None


def _related_fixes(scan_issues, spec):
    """Open, auto-fixable scan issues matching [(check, title filter)]."""
    out, seen = [], set()
    for entry in spec:
        check_key, needle = entry[0], (entry[1].lower() if len(entry) > 1 else None)
        for i in scan_issues or []:
            if i.category == CAT_GPU or i.children or i.check != check_key or i.id in seen:
                continue
            if not i.fixable or (needle and needle not in (i.title + " " + i.obj).lower()):
                continue
            seen.add(i.id)
            out.append(i)
    return out


