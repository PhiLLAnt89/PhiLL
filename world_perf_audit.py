_STATE = {"issues": [], "stats": OrderedDict(), "errors": [], "level": ""}


def _get_actors(selected_only=False):
    """Every actor of the editor world: persistent level + all LOADED sublevels (visible or hidden),
    Level Instance contents, child actors and currently spawned Sequencer spawnables."""
    sub = unreal.get_editor_subsystem(unreal.EditorActorSubsystem)
    if selected_only:
        return [a for a in (sub.get_selected_level_actors() or []) if a is not None]
    actors, seen = [], set()

    def add(items):
        for a in items or []:
            if a is None or _isinst(a, "WorldSettings"):
                continue
            try:
                key = a.get_path_name()
            except Exception:
                continue
            if key not in seen:
                seen.add(key)
                actors.append(a)

    add(sub.get_all_level_actors())
    # get_all_level_actors skips non-editable/transient actors (Level Instance contents, child actors,
    # Sequencer spawnables). The raw world iterator catches those too.
    try:
        add(unreal.GameplayStatics.get_all_actors_of_class(_editor_world(), unreal.Actor))
    except Exception:
        pass
    return actors


def _short_level_name(path):
    path = str(path or "")
    return path.rsplit("/", 1)[-1].split(".")[0] or path


def scan_scope(actors=None):
    """What a scan covers: loaded levels, sublevels that are NOT loaded, World Partition actor counts."""
    world = _editor_world()
    scope = OrderedDict([("actors", len(actors) if actors is not None else len(_get_actors())),
                         ("levels_loaded", []), ("levels_unloaded", []), ("wp_total", None)])
    try:
        scope["levels_loaded"] = [_short_level_name(l.get_outermost().get_name())
                                  for l in (unreal.EditorLevelUtils.get_levels(world) or [])]
    except Exception:
        pass
    cls = _ucls("LevelStreaming")
    if cls is not None and world is not None and hasattr(unreal, "ObjectIterator"):
        for ls in unreal.ObjectIterator(cls):
            try:
                if ls.get_outer() != world or ls.get_loaded_level() is not None:
                    continue
                if _isinst(ls, "LevelStreamingLevelInstance", "LevelStreamingLevelInstanceEditor"):
                    continue
                name = _call_first(lambda: ls.get_world_asset_package_name(),
                                   lambda: _prop(ls, "world_asset"), lambda: ls.get_name())
                scope["levels_unloaded"].append(_short_level_name(name))
            except Exception:
                pass
    wpl = _ucls("WorldPartitionBlueprintLibrary")
    if wpl is not None:
        try:
            res = wpl.get_actor_descs()
            descs = res[-1] if isinstance(res, tuple) else res
            if descs:
                scope["wp_total"] = len(descs)
        except Exception:
            pass
    return scope


def _scope_text(scope):
    parts = ["%d actors" % scope["actors"], "%d level(s) loaded" % max(1, len(scope["levels_loaded"]))]
    if scope["levels_unloaded"]:
        parts.append("%d sublevel(s) NOT loaded (not scanned): %s" % (
            len(scope["levels_unloaded"]), ", ".join(scope["levels_unloaded"][:8])
            + (" ..." if len(scope["levels_unloaded"]) > 8 else "")))
    if scope["wp_total"]:
        parts.append("World Partition: %d actors exist, only loaded regions are scanned" % scope["wp_total"])
    return " \u00b7 ".join(parts)


def scan(selected_only=False, check_keys=None):
    """Run all enabled checks. Returns the issue list (sorted by cost, highest first)."""
    actors = _get_actors(selected_only)
    ctx = ScanContext(actors)
    checks = [c for c in _CHECKS if (c["key"] in check_keys if check_keys else c["enabled"])]
    issues, errors = [], []
    with unreal.ScopedSlowTask(len(checks) + 1, "%s: scanning..." % TOOL_NAME) as task:
        task.make_dialog(True)
        task.enter_progress_frame(1, "Collecting %d actors..." % len(actors))
        for c in checks:
            if task.should_cancel():
                break
            task.enter_progress_frame(1, c["name"])
            try:
                for issue in (c["fn"](ctx) or []):
                    issues.append(issue)
            except Exception:
                errors.append((c["name"], traceback.format_exc()))
                _warn("Check '%s' failed:\n%s" % (c["name"], traceback.format_exc()))
    try:
        ctx.build_stats()
    except Exception:
        pass
    if _STATE.get("gpu_profile") and not selected_only:     # re-link measured GPU findings to the new scan
        try:
            issues += gpu_profile_issues(_STATE["gpu_profile"], issues)
        except Exception:
            _warn("Could not re-link the GPU profile:\n%s" % traceback.format_exc())
    issues.sort(key=lambda i: (-i.cost, -i.severity, i.title))
    world = _editor_world()
    scope = scan_scope(actors)
    _STATE.update(issues=issues, stats=ctx.stats, errors=errors, scope=scope,
                  level=world.get_name() if world else "", selected_only=selected_only)
    _log("Scan done: %d issue(s), %d auto-fixable, %d check error(s). Scope: %s"
         % (len(issues), sum(1 for i in issues if i.fixable), len(errors), _scope_text(scope)))
    if scope["levels_unloaded"]:
        _warn("Not scanned - sublevels not loaded: %s" % ", ".join(scope["levels_unloaded"]))
    return issues


def apply_fixes(issues, title="World Perf Audit: Fix"):
    """Apply fixes inside one undo transaction. Every changed value is journaled so the fix can be
    reverted later (even after saving). Group issues (GPU findings) apply their children. Returns (fixed, failed)."""
    groups = [i for i in issues if i.children]
    todo, seen = [], set()
    for i in issues:
        for x in (i.children if i.children else [i]):
            if x.fixable and x.id not in seen:
                seen.add(x.id)
                todo.append(x)
    fixed = failed = 0
    if not todo:
        return 0, 0
    with unreal.ScopedEditorTransaction(title):
        with unreal.ScopedSlowTask(len(todo), "Applying fixes...") as task:
            task.make_dialog(True)
            for issue in todo:
                if task.should_cancel():
                    break
                task.enter_progress_frame(1, "Fixing: %s - %s" % (issue.title, issue.obj))
                rec = ChangeRecorder()
                try:
                    msg = issue.fix(rec)
                    issue.status, issue.message = "fixed", (msg or issue.fix_label)
                    fixed += 1
                    _log("Fix applied #%d %s (%s): %s" % (issue.id, issue.title, issue.obj, issue.message))
                except Exception as e:
                    issue.status, issue.message = "failed", str(e)
                    failed += 1
                    _warn("Fix failed #%d %s (%s): %s\n%s" % (issue.id, issue.title, issue.obj, e,
                                                              traceback.format_exc()))
                if rec.changes:   # journal even partial fixes, so they can be reverted too
                    issue.journal = {
                        "id": uuid.uuid4().hex, "time": datetime.datetime.now().isoformat(),
                        "level": _STATE.get("level", ""), "check": issue.check, "title": issue.title,
                        "obj": issue.obj, "impact": issue.impact, "changes": rec.changes, "reverted": False}
                    _journal_write(issue.journal)
    _update_groups(groups)
    return fixed, failed


def _update_groups(groups):
    for g in groups:
        done = [c for c in g.children if c.status == "fixed"]
        failed = [c for c in g.children if c.status == "failed"]
        if done and not any(c.fixable for c in g.children):
            g.status, g.message = "fixed", "Applied %d related fix(es)" % len(done)
        elif done:   # partly applied: keep it open so its Fix button applies the rest
            g.status, g.message = "open", "Applied %d related fix(es), %d still open" % (
                len(done), sum(1 for c in g.children if c.fixable))
        elif failed:
            g.status, g.message = "failed", "; ".join(c.message for c in failed[:3])
        elif g.status == "fixed":
            g.status, g.message = "reverted", "Reverted"


def _revert_entries(entries, title="World Perf Audit: Revert"):
    """Revert journal entries, newest first. Returns (reverted_count, [error strings])."""
    entries = [e for e in entries if _revertable(e)]
    done, errors = 0, []
    if not entries:
        return 0, []
    with unreal.ScopedEditorTransaction(title):
        with unreal.ScopedSlowTask(len(entries), "Reverting fixes...") as task:
            task.make_dialog(True)
            for e in sorted(entries, key=lambda x: x.get("time", ""), reverse=True):
                task.enter_progress_frame(1, "Reverting: %s - %s" % (e.get("title"), e.get("obj")))
                errs = _revert_changes(e.get("changes", []))
                e["reverted"], e["revert_errors"] = True, errs
                _journal_write(e)
                done += 1
                errors += ["%s (%s): %s" % (e.get("title"), e.get("obj"), x) for x in errs]
                _log("Reverted %s (%s)%s" % (e.get("title"), e.get("obj"), " with problems: %s" % errs if errs else ""))
    return done, errors


def revert_issues(issues):
    """Revert the last fix of each issue (group issues revert their children). Returns (reverted_count, errors)."""
    groups = [i for i in issues if i.children]
    issues = [x for i in issues for x in (i.children if i.children else [i])]
    done, errors = _revert_entries([i.journal for i in issues if i.revertable])
    for i in issues:
        if i.journal and i.journal.get("reverted") and i.status == "fixed":
            errs = i.journal.get("revert_errors") or []
            i.status, i.message = "reverted", ("Reverted" + (" (partly): " + "; ".join(errs) if errs else ""))
    _update_groups(groups)
    return done, errors


def journal_entries(pending_only=True):
    """Fixes recorded in Saved/PerfAudit/fix_journal.json (all sessions)."""
    return [e for e in _journal_load() if (_revertable(e) if pending_only else True)]


def revert_all():
    """Revert every fix still recorded in the journal - including fixes from earlier sessions."""
    entries = journal_entries()
