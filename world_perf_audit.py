@check("material_complexity", CAT_MATERIAL, "Expensive shaders (instruction count)")
def _check_material_complexity(ctx):
    mel = unreal.MaterialEditingLibrary
    if not CONFIG["material_stats"] or not hasattr(mel, "get_statistics"):
        return
    usage = list(ctx.material_usage().values())[:CONFIG["max_material_stats"]]
    per_base = OrderedDict()
    with unreal.ScopedSlowTask(len(usage), "Reading material shader statistics...") as task:
        task.make_dialog(True)
        for u in usage:
            if task.should_cancel():
                break
            task.enter_progress_frame(1, "Material stats: " + u.material.get_name())
            try:
                st = mel.get_statistics(u.material)
            except Exception:
                continue
            ps = int(_prop(st, "num_pixel_shader_instructions", 0) or 0)
            samplers = int(_prop(st, "num_samplers", 0) or 0)
            if ps <= 0:
                continue
