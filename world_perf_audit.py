# --- materials ---------------------------------------------------------------
_OPAQUE_LIKE = ("BLEND_OPAQUE", "BLEND_MASKED")


def _base_material(mi):
    if mi is None:
        return None
    try:
        return mi.get_base_material()
    except Exception:
        return mi if isinstance(mi, unreal.Material) else None


def _blend_mode_name(mi):
    base = _base_material(mi)
    bm = _prop(base, "blend_mode")
    if isinstance(mi, unreal.MaterialInstance):
        ov = _prop(mi, "base_property_overrides")
        if ov is not None and _prop(ov, "override_blend_mode", False):
            bm = _prop(ov, "blend_mode", bm)
    return _enum_name(bm)


def _is_translucent(mi):
    n = _blend_mode_name(mi)
    return bool(n) and n not in _OPAQUE_LIKE


def _edit_material(base, **props):
    """Set flags on a base material quietly, then do a single recompile."""
    _modify(base)
    for k, v in props.items():
        _set(base, k, v, notify=False)
    unreal.MaterialEditingLibrary.recompile_material(base)


# --- static meshes -----------------------------------------------------------
def _sm_subsystem():
    return _subsystem("StaticMeshEditorSubsystem")


def _nanite_enabled(mesh):
    ns = _prop(mesh, "nanite_settings")
    return bool(_prop(ns, "enabled", False)) if ns is not None else False


def _mesh_tris(mesh, lod=0):
    try:
        return int(mesh.get_num_triangles(lod))
    except Exception:
        pass
    sub = _sm_subsystem()
    try:
        verts = sub.get_number_verts(mesh, lod) if sub else unreal.EditorStaticMeshLibrary.get_number_verts(mesh, lod)
        return int(verts * 1.5)  # rough estimate when the triangle API is missing
    except Exception:
        return 0


def _mesh_lods(mesh):
    try:
        return int(mesh.get_num_lods())
    except Exception:
        sub = _sm_subsystem()
        try:
            return int(sub.get_lod_count(mesh))
        except Exception:
            return 1


def _enable_nanite(mesh):
    _modify(mesh)
    ns = mesh.get_editor_property("nanite_settings")
    ns.set_editor_property("enabled", True)
    sub = _sm_subsystem()
    if sub is not None and hasattr(sub, "set_nanite_settings"):
        sub.set_nanite_settings(mesh, ns, True)
    else:
        mesh.set_editor_property("nanite_settings", ns)  # PostEditChange rebuilds the mesh
    return "Nanite enabled on %s" % mesh.get_name()


def _generate_lods(mesh, count):
    opts_cls = _ucls("StaticMeshReductionOptions") or _ucls("EditorScriptingMeshReductionOptions")
    set_cls = _ucls("StaticMeshReductionSettings") or _ucls("EditorScriptingMeshReductionSettings")
    if opts_cls is None or set_cls is None:
        raise RuntimeError("Mesh reduction API not available (enable Editor Scripting Utilities).")
    settings = []
    pct, screen = 1.0, 1.0
    for _ in range(max(2, count)):
        s = set_cls()
        s.set_editor_property("percent_triangles", pct)
        s.set_editor_property("screen_size", screen)
        settings.append(s)
        pct *= 0.5
        screen *= 0.5
    opts = opts_cls()
    opts.set_editor_property("auto_compute_lod_screen_size", True)
    opts.set_editor_property("reduction_settings", settings)
    _modify(mesh)
    sub = _sm_subsystem()
    if sub is not None and hasattr(sub, "set_lods_with_notification"):
        n = sub.set_lods_with_notification(mesh, opts, True)
    elif sub is not None:
        n = sub.set_lods(mesh, opts)
    else:
        n = unreal.EditorStaticMeshLibrary.set_lods(mesh, opts)
    if n is not None and n < 0:
        raise RuntimeError("LOD generation failed for %s" % mesh.get_name())
    return "Generated %s LODs on %s" % (n if n is not None else count, mesh.get_name())


